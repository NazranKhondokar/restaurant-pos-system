-- Orders
CREATE TABLE IF NOT EXISTS orders (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id INT NOT NULL,
    branch_id INT NOT NULL,
    pos_device_id INT,
    order_number VARCHAR(50) NOT NULL UNIQUE,
    order_token VARCHAR(20),
    order_type VARCHAR(20) NOT NULL, -- DINE_IN, TAKEAWAY, DELIVERY, QR, KIOSK
    order_source VARCHAR(20) NOT NULL, -- POS, QR, KIOSK, ONLINE
    table_id INT,
    customer_id INT,
    customer_name VARCHAR(255),
    customer_phone VARCHAR(50),
    customer_email VARCHAR(255),
    customer_address TEXT,
    guest_count INT,
    waiter_id INT,
    subtotal DECIMAL(10, 2) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(10, 2) NOT NULL DEFAULT 0,
    delivery_fee DECIMAL(10, 2) DEFAULT 0,
    tip_amount DECIMAL(10, 2) DEFAULT 0,
    discount_amount DECIMAL(10, 2) DEFAULT 0,
    total_amount DECIMAL(10, 2) NOT NULL DEFAULT 0,
    payment_status INT NOT NULL DEFAULT 0, -- 0=Pending, 1=Paid, 2=Partial, 3=Refunded
    order_status INT NOT NULL DEFAULT 0, -- 0=Draft, 1=Confirmed, 2=Preparing, 3=Ready, 4=Completed, 5=Cancelled
    notes TEXT,
    cancelled_reason_id INT,
    cancelled_at TIMESTAMP(6) WITH TIME ZONE,
    cancelled_by INT,
    confirmed_at TIMESTAMP(6) WITH TIME ZONE,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) WITH TIME ZONE NULL,
    CONSTRAINT fk_order_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants(id) ON DELETE CASCADE,
    CONSTRAINT fk_order_branch FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE CASCADE,
    CONSTRAINT fk_order_pos_device FOREIGN KEY (pos_device_id) REFERENCES pos_devices(id) ON DELETE SET NULL,
    CONSTRAINT fk_order_waiter FOREIGN KEY (waiter_id) REFERENCES staff(id) ON DELETE SET NULL
);

-- Order Items
CREATE TABLE IF NOT EXISTS order_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT NOT NULL,
    menu_item_id INT NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    unit_price DECIMAL(10, 2) NOT NULL,
