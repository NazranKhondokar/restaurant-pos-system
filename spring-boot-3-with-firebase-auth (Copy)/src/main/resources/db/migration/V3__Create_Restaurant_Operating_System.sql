-- Cash Sessions
CREATE TABLE IF NOT EXISTS cash_sessions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id INT NOT NULL,
    branch_id INT NOT NULL,
    pos_device_id INT NOT NULL,
    staff_id INT NOT NULL,
    session_number VARCHAR(50) NOT NULL UNIQUE,
    opening_balance DECIMAL(10, 2) NOT NULL DEFAULT 0,
    expected_closing_balance DECIMAL(10, 2) DEFAULT 0,
    actual_closing_balance DECIMAL(10, 2),
    discrepancy DECIMAL(10, 2) DEFAULT 0,
    total_cash_in DECIMAL(10, 2) DEFAULT 0,
    total_cash_out DECIMAL(10, 2) DEFAULT 0,
    total_safe_drop DECIMAL(10, 2) DEFAULT 0,
    session_status INT NOT NULL DEFAULT 1, -- 1=Open, 2=Closed, 3=Pending_Approval
    approved_by INT,
    approved_at TIMESTAMP(6) WITH TIME ZONE,
    notes TEXT,
    opened_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    closed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) WITH TIME ZONE NULL,
    CONSTRAINT fk_cash_session_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants(id) ON DELETE CASCADE,
    CONSTRAINT fk_cash_session_branch FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE CASCADE,
    CONSTRAINT fk_cash_session_pos FOREIGN KEY (pos_device_id) REFERENCES pos_devices(id) ON DELETE RESTRICT,
    CONSTRAINT fk_cash_session_staff FOREIGN KEY (staff_id) REFERENCES staff(id) ON DELETE RESTRICT,
    CONSTRAINT fk_cash_session_approver FOREIGN KEY (approved_by) REFERENCES staff(id) ON DELETE SET NULL
);

-- Cash Transactions
CREATE TABLE IF NOT EXISTS cash_transactions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_session_id INT NOT NULL,
    transaction_type VARCHAR(50) NOT NULL, -- CASH_IN, CASH_OUT, SAFE_DROP
    amount DECIMAL(10, 2) NOT NULL,
    reason TEXT,
    created_by INT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT fk_cash_trans_session FOREIGN KEY (cash_session_id) REFERENCES cash_sessions(id) ON DELETE CASCADE,
    CONSTRAINT fk_cash_trans_creator FOREIGN KEY (created_by) REFERENCES staff(id) ON DELETE RESTRICT
);

-- Cash Denominations
CREATE TABLE IF NOT EXISTS cash_denominations (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_session_id INT NOT NULL,
    denomination_type VARCHAR(50) NOT NULL, -- OPENING, CLOSING
