    tax_amount DECIMAL(10, 2) DEFAULT 0,
    special_instructions TEXT,
    status INT NOT NULL DEFAULT 0, -- 0=Pending, 1=Confirmed, 2=Cancelled
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) WITH TIME ZONE NULL,
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_order_item_menu FOREIGN KEY (menu_item_id) REFERENCES menu_items(id) ON DELETE RESTRICT
